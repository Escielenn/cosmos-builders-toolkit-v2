// MARKDOWN EXPORT
// ═══════════════════════════════════════════════════════════════════════════

export function exportMarkdown(
  galaxyName: string,
  config: GalaxyConfig,
  empires: Empire[],
  tradeRoutes: TradeRoute[],
  wormholes: Wormhole[],
  stars: Star[],
  blackHole?: BlackHole | null,
): void {
  let md = `# ${galaxyName}\n\n`;
  md += `**Generated by** StellarForge Stellar Cartographer  \n`;
  md += `**Seed:** ${config.seed}  \n`;
  md += `**Type:** ${config.type}  \n`;
  md += `**Stars:** ${config.starCount.toLocaleString()}  \n\n`;

  md += `---\n\n## Empires\n\n`;
  for (const empire of empires) {
    const count = stars.filter(s => s.empire?.id === empire.id).length;
    md += `### ${empire.name}\n`;
    md += `- **Color:** ${empire.color}\n`;
    md += `- **Naming Style:** ${empire.namingStyle}\n`;
    md += `- **Systems:** ${count.toLocaleString()}\n\n`;
  }

  if (tradeRoutes.length > 0) {
    md += `---\n\n## Trade Routes\n\n`;
    for (const route of tradeRoutes) {
      md += `### ${route.name}\n`;
      md += `- **Waypoints:** ${route.stars.map(s => s.name).join(' → ')}\n\n`;
    }
  }

  if (wormholes.length > 0) {
    md += `---\n\n## Wormholes\n\n`;
    for (const wh of wormholes) {
      md += `### ${wh.name}\n`;
      md += `- **Connection:** ${wh.starA.name} ↔ ${wh.starB.name}\n`;
      md += `- **Stability:** ${wh.stable ? 'Stable' : 'Unstable'}\n\n`;
    }
  }

  if (blackHole) {
    md += `---\n\n## Galactic Nucleus\n\n`;
    md += `### ${blackHole.name}\n`;
    md += `- **Mass:** ${blackHole.mass.toLocaleString()}M☉ (million solar masses)\n`;
    md += `- **Activity:** ${blackHole.activity.charAt(0).toUpperCase() + blackHole.activity.slice(1)}\n`;
    md += `- **Position:** (${blackHole.x.toFixed(0)}, ${blackHole.y.toFixed(0)})\n\n`;
  }

  md += `---\n\n## Notable Habitable Systems\n\n`;
  const habitableStars = stars.filter(s => s.hasHabitable).slice(0, 30);
  for (const star of habitableStars) {
    md += `- **${star.name}** — Class ${star.type}`;
    if (star.empire) md += ` (${star.empire.name})`;
    md += `\n`;
  }

  md += `\n---\n\n*These worlds exist in you. Waiting to be found.*\n\n`;
  md += `© 2025-2026 Jason D. Batt, Ph.D. · StellarForge.tools\n`;

  const blob = new Blob([md], { type: 'text/markdown' });
  const link = document.createElement('a');
  const filename = sanitizeFilename(galaxyName) || 'galaxy';
  link.download = `${filename}_documentation.md`;
  link.href = URL.createObjectURL(blob);
  link.click();
  URL.revokeObjectURL(link.href);
}

