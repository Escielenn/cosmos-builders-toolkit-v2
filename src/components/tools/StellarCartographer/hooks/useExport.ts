export function exportPNG(
  canvas: HTMLCanvasElement,
  galaxyName: string,
  renderFn: (ctx: CanvasRenderingContext2D, width: number, height: number) => void
): void {
  const scale = 2; // 2x resolution for high quality
  const exportCanvas = document.createElement('canvas');
  exportCanvas.width = canvas.width * scale;
  exportCanvas.height = canvas.height * scale;
  const ctx = exportCanvas.getContext('2d');
  if (!ctx) return;

  ctx.scale(scale, scale);
  renderFn(ctx, canvas.width, canvas.height);

  // Add watermark
  ctx.font = '600 14px "Space Grotesk", sans-serif';
  ctx.fillStyle = 'rgba(255, 255, 255, 0.4)';
  ctx.textAlign = 'left';
  ctx.fillText(galaxyName, 20, 30);
  
  ctx.font = '400 9px "DM Sans", sans-serif';
  ctx.fillStyle = 'rgba(255, 255, 255, 0.25)';
  ctx.fillText('Generated by StellarForge.tools', 20, 45);

  // Download
  const link = document.createElement('a');
  const filename = sanitizeFilename(galaxyName) || 'galaxy';
  link.download = `${filename}_map.png`;
  link.href = exportCanvas.toDataURL('image/png');
  link.click();
}

